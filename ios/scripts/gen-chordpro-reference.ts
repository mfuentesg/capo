// Generates ChordProReferenceData.swift from the web directive docs:
//   npx tsx ios/scripts/gen-chordpro-reference.ts
import { writeFileSync } from "node:fs"
import path from "node:path"
import {
  CHORDPRO_DIRECTIVES,
  SECTION_FLAG_DOCS
} from "../../features/lyrics-editor/data/chordpro-directives"

const root = path.resolve(__dirname, "../..")
const q = (s: string) => JSON.stringify(s).replace(/\\u([0-9a-f]{4})/g, (_, h) => String.fromCharCode(parseInt(h, 16)))
const swiftString = (s: string) => {
  // Swift string literal with \u{} escapes for characters JSON would escape differently.
  return `"${s.replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\n/g, "\\n")}"`
}
void q

const directives = CHORDPRO_DIRECTIVES.map(
  (d) =>
    `    ReferenceDirective(\n      name: ${swiftString(d.name)}, shorthand: ${d.shorthand ? swiftString(d.shorthand) : "nil"},\n      category: .${d.category},\n      summary: ${swiftString(d.description)},\n      example: ${swiftString(d.example)})`
).join(",\n")
const flags = SECTION_FLAG_DOCS.map(
  (f) =>
    `    ReferenceFlag(\n      flag: ${swiftString(f.flag)}, summary: ${swiftString(f.description)},\n      example: ${swiftString(f.example)})`
).join(",\n")

writeFileSync(
  path.join(root, "ios/Packages/CapoUI/Sources/CapoEditorUI/Reference/ChordProReferenceData.swift"),
  `// Generated by ios/scripts/gen-chordpro-reference.ts from features/lyrics-editor/data/chordpro-directives.ts.
// Do not edit.

nonisolated enum ReferenceData {
  static let directives: [ReferenceDirective] = [
${directives}
  ]

  static let flags: [ReferenceFlag] = [
${flags}
  ]
}
`
)
console.log(CHORDPRO_DIRECTIVES.length, SECTION_FLAG_DOCS.length)
