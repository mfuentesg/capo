// Generates the glossary order (GlossaryOrder.swift) and identifier golden (chords.json) from the web:
//   npx tsx ios/scripts/gen-chords-glossary.ts
import { writeFileSync } from "node:fs"
import path from "node:path"
import { getAllChords } from "../../features/chords/utils/chord-db-helpers"
import { identifyChord, getNotesFromFrets } from "../../features/chords/utils/chord-identifier"

const root = path.resolve(__dirname, "../..")
const order: Record<string, string[]> = {}
for (const c of getAllChords()) (order[c.key] ??= []).push(c.suffix)
const lines = Object.entries(order).map(
  ([k, v]) => `    (${JSON.stringify(k)}, [${v.map((s) => JSON.stringify(s)).join(", ")}])`
)
writeFileSync(
  path.join(root, "ios/Packages/CapoUI/Sources/CapoChordsUI/GlossaryOrder.swift"),
  `// Generated by ios/scripts/gen-chords-glossary.ts from the web chord DB order. Do not edit.

enum GlossaryOrder {
  /// Database keys with their suffixes, in the web glossary's order.
  static let entries: [(key: String, suffixes: [String])] = [
${lines.join(",\n")}
  ]
}
`
)

let seed = 7
const rnd = () => ((seed = (seed * 1664525 + 1013904223) % 4294967296) / 4294967296)
const cases = Array.from({ length: 400 }, () => {
  const frets = Array.from({ length: 6 }, () => {
    const r = rnd()
    return r < 0.2 ? -1 : r < 0.4 ? 0 : 1 + Math.floor(rnd() * 5)
  })
  const baseFret = 1 + Math.floor(rnd() * 12)
  return { frets, baseFret, results: identifyChord(frets, baseFret), notes: getNotesFromFrets(frets, baseFret) }
})
writeFileSync(path.join(root, "ios/Fixtures/converter/chords.json"), JSON.stringify(cases))
console.log(Object.keys(order).length, cases.filter((c) => c.results.length).length)
