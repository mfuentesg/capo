const PALETTE_THEME_VARS: Record<string, PaletteTheme> = {
  catppuccin,
  aura,
  nord,
  "rose-pine": rosePine,
  dracula,
  "one-dark-pro": oneDarkPro,
  "tokyo-night": tokyoNight,
  gruvbox
}

function serializeVars(vars: Vars): string {
  return Object.entries(vars)
    .map(([k, v]) => `${k}:${v}`)
    .join(";")
}

/**
 * Generates an inline CSS string for the given palette containing both the
 * light and dark variable definitions. Injected as a `<style>` in `<head>`,
 * this makes the palette available from the very first paint without waiting
 * for the external globals.css stylesheet.
 *
 * Uses the same selectors as globals.css so the external sheet overrides
 * cleanly with identical values once it loads — no visual transition.
 */
export function buildPaletteStyle(palette: string): string {
  const theme = PALETTE_THEME_VARS[palette] ?? catppuccin

  const light = serializeVars(theme.light)
  const dark = serializeVars(theme.dark)

  if (palette === "catppuccin") {
    // Catppuccin is the globals.css default; selectors mirror :root and .dark
    return `:root{${light}}.dark{${dark}}`
  }

  const lightSel = `html[data-palette="${palette}"]`
  const darkSel = `html[data-palette="${palette}"].dark`
  return `${lightSel}{${light}}${darkSel}{${dark}}`
}
